#[cfg(windows)]
pub(crate) fn scancode(code: u32, extended: bool) -> Option<u32> {
    if !extended {
        return match code {
            0x45 => Some(119),
            1..=0x58 => Some(code),
            _ => None,
        };
    }
    Some(match code {
        0x45 => 69,
        0x1c => 96,
        0x1d => 97,
        0x35 => 98,
        0x37 => 99,
        0x38 => 100,
        0x47 => 102,
        0x48 => 103,
        0x49 => 104,
        0x4b => 105,
        0x4d => 106,
        0x4f => 107,
        0x50 => 108,
        0x51 => 109,
        0x52 => 110,
        0x53 => 111,
        0x5b => 125,
        0x5c => 126,
        0x5d => 127,
        _ => return None,
    })
}

