pub(crate) fn by_name(name: &str) -> Option<u32> {
    let lower = name.to_ascii_lowercase();
    let name = ALIASES.iter().find(|(a, _)| *a == lower).map_or(lower.as_str(), |(_, n)| n);
    NAMES.iter().find(|(_, n)| *n == name).map(|&(evdev, _)| evdev)
}

